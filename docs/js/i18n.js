// Idiomas del juego: español (España) e inglés (EE. UU.).
// El texto fuente es el español: t('Crear sala') devuelve 'Create room' en inglés.
// Cada móvil usa su idioma; el anfitrión y los invitados pueden jugar en idiomas distintos
// porque lo que viaja por la red son datos (números, ids), no frases.
// test/i18n.mjs comprueba que no falta ninguna traducción.

const KEY = 'tr-lang';
export const LANGS = ['es', 'en'];

function detect() {
  try {
    const q = new URLSearchParams(location.search).get('lang');
    if (LANGS.includes(q)) return q;
  } catch (e) {
    /* fuera del navegador */
  }
  try {
    const s = localStorage.getItem(KEY);
    if (LANGS.includes(s)) return s;
  } catch (e) {
    /* sin almacenamiento */
  }
  try {
    const nav = (navigator.languages && navigator.languages[0]) || navigator.language || '';
    if (!nav) return 'es';
    return /^es\b/i.test(nav) ? 'es' : 'en';
  } catch (e) {
    return 'es';
  }
}

let lang = detect();
export const getLang = () => lang;

function applyDoc() {
  try {
    document.documentElement.lang = lang;
    document.title = t('Trasteros: subastas a ciegas');
  } catch (e) {
    /* fuera del navegador */
  }
}

export function setLang(l) {
  if (!LANGS.includes(l)) return;
  lang = l;
  try {
    localStorage.setItem(KEY, l);
  } catch (e) {
    /* sin almacenamiento */
  }
  applyDoc();
}

export function t(s, vars) {
  let r = lang === 'en' && EN[s] != null ? EN[s] : s;
  if (vars) r = r.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return r;
}
// singular / plural (en los dos idiomas vale «1 = singular»)
export const tn = (n, one, many, vars) => t(n === 1 ? one : many, { n, ...vars });

// nombres propios de bots, rivales y la casa (los de las personas no se tocan)
export const tname = (s) => (lang === 'en' && NAMES_EN[s] ? NAMES_EN[s] : s);

const fmtES = new Intl.NumberFormat('es-ES');
const fmtEN = new Intl.NumberFormat('en-US');
export const num = (n) => (lang === 'en' ? fmtEN : fmtES).format(Math.round(n));
export function money(n) {
  const v = Math.round(n);
  if (lang === 'en') return `${v < 0 ? '-' : ''}$${fmtEN.format(Math.abs(v))}`;
  return `${fmtES.format(v)} €`;
}

